-- PLAN 작업 4 — 5개 업무 스키마·테이블·staff 뷰·업무별 DB 역할
-- Design Ref: §3 합성 DB 설계, §4.3 쿼리 전용 에이전트(업무별 권한으로 다른 업무 차단)
-- 실행: npm run db:migrate -- supabase/migrations/0001_domain_schemas.sql
-- 한 트랜잭션으로 실행되므로 중간에 실패하면 아무것도 남지 않는다.
-- 모든 날짜는 PRD 기준 2026-01-01 ~ 2026-10-31 안에서만 허용한다.

-- ── 스키마 ────────────────────────────────────────────────
create schema hr;
create schema finance;
create schema sales;
create schema security;
create schema dev;

-- ── 인사 hr ───────────────────────────────────────────────
create table hr.employees (
  id         integer generated by default as identity primary key,
  name       text not null,
  department text not null check (department in ('인사팀', '재무팀', '영업팀', '보안팀', '개발팀')),
  position   text not null check (position in ('사원', '대리', '과장', '차장', '부장')),
  hired_at   date not null check (hired_at between '2026-01-01' and '2026-10-31')
);

create table hr.leaves (
  id          integer generated by default as identity primary key,
  employee_id integer not null references hr.employees (id),
  leave_type  text not null check (leave_type in ('연차', '반차', '병가', '경조사')),
  start_date  date not null check (start_date between '2026-01-01' and '2026-10-31'),
  end_date    date not null check (end_date between '2026-01-01' and '2026-10-31'),
  days        numeric(3, 1) not null check (days > 0),
  status      text not null check (status in ('신청', '승인', '반려')),
  check (end_date >= start_date)
);

-- ── 재무 finance ──────────────────────────────────────────
-- cost(총비용)는 인건비를 포함한다. 영업이익은 매출 - 총비용으로 자동 계산한다.
create table finance.monthly_pnl (
  month            date primary key
                   check (month = date_trunc('month', month)::date
                          and month between '2026-01-01' and '2026-10-01'),
  revenue          bigint not null check (revenue >= 0),
  cost             bigint not null check (cost >= 0),
  labor_cost       bigint not null check (labor_cost >= 0 and labor_cost <= cost),
  operating_profit bigint generated always as (revenue - cost) stored
);

create table finance.dept_budgets (
  id         integer generated by default as identity primary key,
  department text not null check (department in ('인사팀', '재무팀', '영업팀', '보안팀', '개발팀')),
  month      date not null
             check (month = date_trunc('month', month)::date
                    and month between '2026-01-01' and '2026-10-01'),
  category   text not null check (category in ('인건비', '운영비')),
  budget     bigint not null check (budget >= 0),
  spent      bigint not null check (spent >= 0),
  unique (department, month, category)
);

-- ── 영업 sales ────────────────────────────────────────────
create table sales.customers (
  id       integer generated by default as identity primary key,
  name     text not null unique,
  industry text not null,
  region   text not null
);

create table sales.contracts (
  id                integer generated by default as identity primary key,
  customer_id       integer not null references sales.customers (id),
  owner_employee_id integer not null references hr.employees (id),
  contract_date     date not null check (contract_date between '2026-01-01' and '2026-10-31'),
  amount            bigint not null check (amount >= 0),
  stage             text not null check (stage in ('문의', '제안', '협상', '계약', '실패'))
);

-- ── 보안 security ─────────────────────────────────────────
-- PRD의 "보안 점검·사고 이력"을 한 테이블에 담고 category로 구분한다.
create table security.security_events (
  id            integer generated by default as identity primary key,
  occurred_at   date not null check (occurred_at between '2026-01-01' and '2026-10-31'),
  category      text not null check (category in ('점검', '사고')),
  type          text not null check (type in (
                  '정기 점검', '취약점 점검', '모의 해킹',         -- 점검
                  '악성코드', '피싱', '계정 도용', '정보 유출'     -- 사고
                )),
  severity      text not null check (severity in ('낮음', '보통', '높음', '심각')),
  action_status text not null check (action_status in ('미조치', '조치중', '조치완료'))
);

create table security.access_requests (
  id                    integer generated by default as identity primary key,
  requester_employee_id integer not null references hr.employees (id),
  system_name           text not null,
  requested_at          date not null check (requested_at between '2026-01-01' and '2026-10-31'),
  status                text not null check (status in ('요청', '승인', '반려'))
);

-- ── 개발 dev ──────────────────────────────────────────────
create table dev.projects (
  id               integer generated by default as identity primary key,
  name             text not null unique,
  lead_employee_id integer not null references hr.employees (id),
  start_date       date not null check (start_date between '2026-01-01' and '2026-10-31'),
  status           text not null check (status in ('계획', '진행', '완료', '보류'))
);

create table dev.issues (
  id                   integer generated by default as identity primary key,
  project_id           integer not null references dev.projects (id),
  title                text not null,
  status               text not null check (status in ('할일', '진행중', '완료')),
  priority             text not null check (priority in ('낮음', '보통', '높음', '긴급')),
  assignee_employee_id integer not null references hr.employees (id),
  created_at           date not null check (created_at between '2026-01-01' and '2026-10-31')
);

-- ── staff 뷰: 다른 업무가 직원 이름만 볼 수 있게 ──────────
create view sales.staff    as select id, name, department from hr.employees;
create view security.staff as select id, name, department from hr.employees;
create view dev.staff      as select id, name, department from hr.employees;

-- ── 업무별 DB 역할 ────────────────────────────────────────
-- 로그인은 못 하고, 서버가 트랜잭션마다 SET LOCAL ROLE 로만 쓴다.
-- 각 역할은 자기 업무 스키마의 테이블만 조회·등록·수정·삭제할 수 있고, staff 뷰는 조회만 된다.
-- 테이블 생성·삭제(DDL) 권한은 없다.
create role agent_hr       nologin;
create role agent_finance  nologin;
create role agent_sales    nologin;
create role agent_security nologin;
create role agent_dev      nologin;

-- 접속 사용자(current_user)가 SET ROLE 로 각 역할로 바꿀 수 있게 한다 (권한을 물려받지는 않음)
do $$
declare r text;
begin
  foreach r in array array['agent_hr', 'agent_finance', 'agent_sales', 'agent_security', 'agent_dev'] loop
    execute format('grant %I to %I with inherit false, set true', r, current_user);
  end loop;
end $$;

grant usage on schema hr to agent_hr;
grant select, insert, update, delete on hr.employees, hr.leaves to agent_hr;
grant usage on all sequences in schema hr to agent_hr;

grant usage on schema finance to agent_finance;
grant select, insert, update, delete on finance.monthly_pnl, finance.dept_budgets to agent_finance;
grant usage on all sequences in schema finance to agent_finance;

grant usage on schema sales to agent_sales;
grant select, insert, update, delete on sales.customers, sales.contracts to agent_sales;
grant select on sales.staff to agent_sales;
grant usage on all sequences in schema sales to agent_sales;

grant usage on schema security to agent_security;
grant select, insert, update, delete on security.security_events, security.access_requests to agent_security;
grant select on security.staff to agent_security;
grant usage on all sequences in schema security to agent_security;

grant usage on schema dev to agent_dev;
grant select, insert, update, delete on dev.projects, dev.issues to agent_dev;
grant select on dev.staff to agent_dev;
grant usage on all sequences in schema dev to agent_dev;
